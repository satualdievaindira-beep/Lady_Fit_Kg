const tabs = document.getElementById("tabs");
const panel = document.getElementById("panel");
const sel = document.getElementById("dir");
const fmt = n => n.toLocaleString("ru-RU").replace(/\u00a0/g, " ");
const esc = s => s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

function show(id) {
  const d = D.find(x => x.id === id);
  [...tabs.children].forEach(b => b.setAttribute("aria-selected", b.dataset.id === id));
  const points = d.points ? `<ul>${d.points.map(p => `<li>${esc(p)}</li>`).join("")}</ul>` : "";
  const rows = d.rows.map(([name, sub, price]) => {
    const msg = `Здравствуйте! Хочу записаться в Lady Fit: ${d.title} — ${name}${price ? ` (${fmt(price)} сом)` : ""}.`;
    return `<li><div><b>${esc(name)}</b>${sub ? `<small>${esc(sub)}</small>` : ""}</div>
      <span class="sum">${price ? `${fmt(price)} <small>сом</small>` : ""}</span>
      <a href="${wa(msg)}" target="_blank" rel="noopener">Записаться</a></li>`;
  }).join("");
  panel.innerHTML = `<div class="info"><h3>${esc(d.title)}</h3><p>${esc(d.text)}</p>${points}<p class="when">${esc(d.when)}</p></div><ul class="rows">${rows}</ul>`;
}

D.forEach(d => {
  const b = document.createElement("button");
  b.textContent = d.tab; b.dataset.id = d.id; b.setAttribute("role", "tab");
  b.onclick = () => show(d.id);
  tabs.appendChild(b);
  sel.add(new Option(d.title, d.title));
});
show(D[0].id);

